# f(a,n) = ((a-1)^n + (a+1)^n)
# r(a,n) = f(a,n) % a^2
# f'(a,n) = ln(a-1)(a-1)^n + ln(a+1)(a+1)^n
# -> follows binomial 
# (x+y)^n = (n 0)x^n y^0 + (n 1)x^(n-1) y^1 + (n 2)x^(n-2) y^2 + ... + (n n)x^(n-n) y^n
# (n n) = 1, (n n-1) = n

# (a+1)^n = (n 0)(a^n)(1^0) + (n 1)(a^(n-1))(1^1) + ... (n n)(a^0)(1^n) 
#         = (n 0)a^n + (n 1)(a^(n-1)) + (n 2)(a^(n-2)) + ... + (n n)(1)(1)
# (a+1)^n % a^n = (n 0)a^n % a^2 + (n 1)(a^(n-1)) % a^2 + (n 2)(a^(n-2)) % a^2 + ... + (n n)(1)(1) % a^2
#               = 0 + 0 + ... + (n n-1)a^1 % a^2 + (n n)a^0 % a^2
#               = na + 1

# (a-1)^n = (n 0)(a^n)(-1^0) + (n 1)(a^(n-1))(-1^1) + ... (n n)(a^0)(-1^n) 
#         = (n 0)a^n - (n 1)(a^(n-1)) + (n 2)(a^(n-2)) + ... + (n n)(-1^n)
# (a-1)^n % a^n = (n 0)a^n % a^2 + (n 1)(a^(n-1))(-1) % a^2 + ... + (n n)(1)(1) % a^2
#               = 0 + 0 + ... + (n n-1)(a^1)(-1^(n-1)) % a^2 + (n n)(a^0)(-1^n) % a^2
#               = na(-1^(n-1)) % a^2 + -1^n

# r(a,n) = na + 1 + na(-1^(n-1)) + -1^n
# n % 2 == 0: na + 1 - na + 1 = 2
# n % 2 != 0: 2na % a^2 = 2n % a
# max(r(a,n)) @ 2n = a-1 -> n = (a-1)/2
# max(r(a,n)) = 2a((a-1)/2)

A = 1000
S = 0
for a in range(3,A+1):
    S += (2 * a * ((a-1) // 2))
print(S)



